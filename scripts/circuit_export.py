"""Export the actual GUI and its dependencies without Evolution-only RAM wiring."""

import xml.etree.ElementTree as ET


def demo_project(source: str) -> str:
    """Keep exact circuit definitions reachable from MonitorGUI, not a redraw."""
    project = ET.fromstring(source)
    circuits = {node.get("name"): node for node in project.findall("circuit")}
    pending = ["MonitorGUI"]
    reachable: set[str] = set()
    while pending:
        name = pending.pop()
        if name in reachable:
            continue
        if name not in circuits:
            raise ValueError(f"Missing demo subcircuit: {name}")
        reachable.add(name)
        pending.extend(
            component.get("name")
            for component in circuits[name].findall("comp")
            if component.get("lib") is None
        )
    for name, node in circuits.items():
        if name not in reachable:
            project.remove(node)
    used_libraries = {
        component.get("lib")
        for circuit in project.findall("circuit")
        for component in circuit.findall("comp")
        if component.get("lib") is not None
    }
    used_libraries.update(tool.get("lib") for tool in project.findall("toolbar/tool"))
    for library in project.findall("lib"):
        if library.get("name") not in used_libraries:
            project.remove(library)
    project.find("main").set("name", "MonitorGUI")
    project.text = (
        "Standalone volcano demonstration. Exact MonitorGUI and supporting circuits; "
        "generated by scripts/build_monitor.py. Backend RAM replay is separate.\n"
    )
    ET.indent(project, space="  ")
    return ET.tostring(project, encoding="unicode") + "\n"

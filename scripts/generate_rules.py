"""Generate deterministic rule constants, with a read-only stale-file check."""

import argparse
from pathlib import Path

try:
    from .common import ROOT, read_json, rule_digest
except ImportError:
    from common import ROOT, read_json, rule_digest


def render(rules: dict) -> dict[str, str]:
    """Build assembly and TypeScript views of the same canonical rules."""
    import json

    constants = {
        "RULE_VERSION": rules["rule_version"],
        "PROTOCOL_VERSION": rules["protocol"]["version"],
        "INPUT_MAX": rules["input"]["normal_maximum"],
        "TRANSPORT_MAX": rules["input"]["transport_maximum"],
        "CONNECTED_MASK": rules["input"]["connected_mask"],
        "WINDOW_SAMPLES": rules["sampling"]["window_samples"],
        "MAX_SAMPLES": rules["sampling"]["maximum_samples"],
        "AVERAGE_SCALE": rules["statistics"]["average_scale"],
        "LOGISIM_MAGIC": int(rules["protocol"]["logisim_magic"], 16),
        "ASSEMBLY_MAGIC": int(rules["protocol"]["assembly_magic"], 16),
    }
    constants.update({f"THRESHOLD_{name}": rules["sensors"][name]["threshold"]
                      for name in rules["sensor_order"]})
    constants.update({f"WARNING_{name}": value for name, value in rules["warnings"].items()})
    digest = rule_digest(rules)
    assembly = f"# Generated by scripts/generate_rules.py; do not edit.\n# rules_sha256={digest}\n"
    assembly += "".join(f".equ VM_{name}, {value}\n" for name, value in constants.items())
    frontend = "// Generated by scripts/generate_rules.py; do not edit.\n"
    frontend += f"export const RULES_SHA256 = '{digest}';\n"
    frontend += f"export const RULES = {json.dumps(rules, indent=2)} as const;\n"
    return {"assembly/rules.inc": assembly, "frontend/src/generated-rules.ts": frontend}


def generate(root: Path, *, check: bool) -> list[str]:
    stale = []
    for name, expected in render(read_json(root / "spec/rules.json")).items():
        path = root / name
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8")
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = generate(ROOT, check=args.check)
    if stale and args.check:
        print("Stale generated rules: " + ", ".join(stale) + "; run make generate-rules")
        return 1
    print("Generated rules are current." if args.check else "Generated assembly and frontend rules.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
